import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const dir = fs.readdirSync('E:/个人AI资源管理/60_公用资源（钩子·skill·搜索引擎·可后期扩展）').find((n) => n.startsWith('模型API密钥'));
